export function findIcd10ByCode(code: string): Icd10Entry | undefined {
  return icd10Catalog.find((e) => e.code === code);
}

export function searchIcd10(query: string, limit = 50): Icd10Entry[] {
  const q = query.toLowerCase();
  const results: Icd10Entry[] = [];
  for (const entry of icd10Catalog) {
    if (entry.code.toLowerCase().includes(q) || entry.description.toLowerCase().includes(q)) {
      results.push(entry);
      if (results.length >= limit) break;
    }
  }
  return results;
}
